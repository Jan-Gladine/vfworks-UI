"""Script exporter: renders the open frame as an equivalent hand-editable populatePackage.py."""
from __future__ import annotations

import re

from vfbuilder import vfw
from vfbuilder.frame import FrameSession, custom_code_file


class _Names:
    """Readable, unique Python variable names for elements."""

    def __init__(self) -> None:
        self._by_guid: dict[str, str] = {}
        self._used: set[str] = {"VF", "_id"}

    def assign(self, prefix: str, element) -> str:
        base = re.sub(r"\W+", "_", element.name or "").strip("_") or "unnamed"
        name = f"{prefix}_{base}"
        candidate, n = name, 2
        while candidate in self._used:
            candidate, n = f"{name}_{n}", n + 1
        self._used.add(candidate)
        self._by_guid[element.GUID] = candidate
        return candidate

    def __getitem__(self, guid: str) -> str:
        return self._by_guid[guid]

    def get(self, guid: str) -> str | None:
        return self._by_guid.get(guid)


def _call(func: str, **kwargs: str) -> str:
    return f"{func}({', '.join(f'{k}={v}' for k, v in kwargs.items())})"


def _const(enum_class: str, value) -> str:
    """``PropertyType.PROPERTY_MIN`` for a known value, the literal otherwise."""
    name = vfw.enum_name(enum_class, value)
    return f"{enum_class}.{name}" if name else repr(value)


def render_script(session: FrameSession) -> str:
    """Python source that rebuilds the package when run from the directory that should hold it."""
    names = _Names()
    out: list[str] = []
    emit = out.append

    def with_id(expr: str, element) -> str:
        return f"_id({expr}, {element.GUID!r})"

    def quantity(element) -> dict[str, str]:
        return dict(domain=_const("DomainType", element.domain), unit=_const("UnitType", element.unit),
                    datatype=_const("DataType", element.datatype), min=repr(element.min), max=repr(element.max))

    emit('"""Generated by vfbuilder: builds the validity frame package with vfworks.')
    emit("")
    emit('Run from the directory that should contain the package."""')
    emit("import matplotlib")
    emit("")
    emit('matplotlib.use("Agg")  # vfworks imports pyplot; keep it from opening windows')
    emit("")
    for module in ("specification", "validity_frame", "model_structure", "monitors", "properties", "experiment"):
        emit(f"from vfworks.metamodels.{module} import *")
    emit("")
    emit("")
    emit("def _id(element, guid):")
    emit('    """Pin the GUID so re-running the script does not change element identities."""')
    emit("    element.GUID = guid")
    emit("    return element")
    emit("")
    emit("")
    emit("VF = " + _call("ValidityFrame", name=repr(session.vf.name), description=repr(session.vf.description),
                         VFPackage=repr(session.package_name)))

    if session.experiments:
        emit("")
        emit("# --- experiments")
    for exp in session.experiments:
        var = names.assign("exp", exp)
        emit(f"{var} = " + with_id(_call("Experiment", name=repr(exp.name), description=repr(exp.description),
                                         label=repr(exp.label)), exp))
        for cond in exp.conditions:
            emit(f"{var}.addCondition(" + with_id(_call(
                "ExperimentCondition", name=repr(cond.name), description=repr(cond.description),
                value=repr(cond.value)), cond) + ")")
        for meas in exp.measurements:
            meas_var = names.assign("meas", meas)
            emit(f"{meas_var} = " + with_id(_call(
                "Measurement", name=repr(meas.name), description=repr(meas.description),
                dataPoints=repr(list(meas.dataPoints or [])), reference=repr(meas.reference)), meas))
            emit(f"{var}.addMeasurement({meas_var})")
        emit(f"VF.addExperiment({var})")

    if session.specifications:
        emit("")
        emit("# --- specifications")
    for spec in session.specifications:
        var = names.assign("spec", spec)
        values = {k: repr(int(v) if k == "granularity" else v) for k, v in session.spec_values(spec).items()}
        emit(f"{var} = " + with_id(_call(
            "Specification", name=repr(spec.name), description=repr(spec.description), feature=repr(spec.feature),
            type=_const("PropertyType", spec.type), **values), spec))
        emit(f"VF.addSpecification({var})")

    if session.properties:
        emit("")
        emit("# --- properties")
    for prop in session.properties:
        influence = session.is_influence_factor(prop)
        var = names.assign("if" if influence else "poi", prop)
        satisfies = [names[g] for g in prop.satisfies or [] if names.get(g)]
        emit(f"{var} = " + with_id(_call(
            "InfluenceFactor" if influence else "PropertyofInterest", name=repr(prop.name),
            description=repr(prop.description), **quantity(prop), satisfies="[" + ", ".join(satisfies) + "]"), prop))
        emit(f"VF.addProperty({var})")

    links = [(meas, meas.poi) for exp in session.experiments for meas in exp.measurements if names.get(meas.poi or "")]
    if links:
        emit("")
        emit("# --- measurement links")
    for meas, poi in links:
        emit(f"{names[meas.GUID]}.poi = {names[poi]}.GUID")

    if session.model_structures:
        emit("")
        emit("# --- model structures")
    for ms in session.model_structures:
        ports = {"in": [], "out": []}
        for direction, cls, items in (("in", "Inport", ms.inports), ("out", "Outport", ms.outports)):
            for port in items:
                var = names.assign(direction, port)
                emit(f"{var} = " + with_id(_call(cls, name=repr(port.name), description=repr(port.description),
                                                 **quantity(port)), port))
                if names.get(port.mapping or ""):
                    emit(f'{var}.add_mapping_relation(type="poi", poi={names[port.mapping]})')
                ports[direction].append(var)
        var = names.assign("ms", ms)
        emit(f"{var} = " + with_id(_call(
            "ModelStructure", name=repr(ms.name), description=repr(ms.description),
            inports="[" + ", ".join(ports["in"]) + "]", outports="[" + ", ".join(ports["out"]) + "]",
            modelType=repr(ms.modelType), modelRef=repr(ms.modelRef), redundancy=repr(ms.redundancy)), ms))
        emit(f"VF.addModelStructure({var})")

    if session.monitors:
        emit("")
        emit("# --- monitors")
    for mon in session.monitors:
        var = names.assign("monitor", mon)
        emit(f"{var} = " + with_id(_call(
            "Monitor", name=repr(mon.name), description=repr(mon.description),
            observes="[" + ", ".join(names[s.GUID] for s in mon.observes or []) + "]",
            monitor_time=_const("MonitorTime", mon.type), custom_code_file=repr(custom_code_file(mon))), mon))
        emit(f"VF.addMonitor({var})")

    emit("")
    emit("VF.export()")
    emit("VF.close()")
    return "\n".join(out) + "\n"
